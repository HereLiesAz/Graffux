"""Build the Graffux icon set.

Reads the authored geometry in `sets/`, validates it against the design system, and emits:

  branding/icons/dist/svg/<key>.svg                       — masters, for design tools
  branding/icons/dist/icons.json                          — the manifest (keys, categories, keywords)
  branding/icons/dist/contact-sheet.html                  — reviewable sheet, 24px and 16px
  core/design/src/main/res/drawable/ic_gx_<key>.xml       — Android VectorDrawables
  core/design/.../design/GraffuxIcons.kt                  — typed registry for Compose

Run from anywhere:  python3 branding/icons/build.py
"""

