def contact_sheet(icons):
    by_cat = {}
    for ic in icons:
        by_cat.setdefault(ic["cat"], []).append(ic)

    out = [
        "<title>Graffux Icons</title>",
        f"<style>{SHEET_CSS}</style>",
        '<div class="wrap">',
        "<header>",
        "<h1>Graffux icon set</h1>",
        '<p class="sub">One stroke weight, one grid, one solid mark per glyph. '
        "Built for a phone screen at arm's length.</p>",
        '<div class="meta">'
        f"<span><b>{len(icons)}</b> icons</span>"
        f"<span><b>{len(by_cat)}</b> families</span>"
        f"<span>grid <b>{int(VIEW)}×{int(VIEW)}</b></span>"
        f"<span>live area <b>{int(LIVE[0])}–{int(LIVE[1])}</b></span>"
        f"<span>stroke <b>{STROKE}</b></span>"
        f"<span>cap/join <b>{CAP}</b></span>"
        "</div>",
        "</header>",
        '<div class="controls">',
        '<input id="q" type="search" placeholder="Search name, keyword, or family…" autocomplete="off">',
        '<button class="toggle" id="gridToggle" type="button">4-unit grid</button>',
        "</div>",
    ]

    for key, title, blurb in CATEGORIES:
        group = by_cat.get(key, [])
        if not group:
            continue
        out.append(f'<section data-cat="{key}">')
        out.append(f'<h2>{html.escape(title)} · <span class="n">{len(group)}</span></h2>')
        out.append(f'<p class="blurb">{html.escape(blurb)}</p>')
        out.append('<div class="grid">')
        for ic in group:
            search = " ".join([ic["key"], key, title, ic["apps"], ic["basis"], *ic["kw"]]).lower()
            tip_text = ic["note"] + (f"\nLineage ({ic['apps']}): {ic['basis']}" if ic["basis"] else "")
            body24 = svg_body(ic, indent="")
            svg_attrs = (
                f'viewBox="0 0 {int(VIEW)} {int(VIEW)}" fill="none" stroke="currentColor" '
                f'stroke-width="{STROKE}" stroke-linecap="{CAP}" stroke-linejoin="{JOIN}"'
            )
            out.append(
                f'<div class="cell" data-s="{html.escape(search, quote=True)}" '
                f'title="{html.escape(tip_text, quote=True)}">'
                f'<div class="art">'
                f'<svg width="24" height="24" {svg_attrs}>{body24}</svg>'
                f'<svg width="16" height="16" {svg_attrs}>{body24}</svg>'
                f"</div>"
                f'<div class="k">{html.escape(ic["key"])}</div>'
                f'<div class="apps">{html.escape(ic["apps"])}</div>'
                "</div>"
            )
        out.append("</div></section>")

    out += [
        '<p class="empty" id="empty" hidden>Nothing matches that.</p>',
        "<footer>Each cell shows the glyph at 24px and at 16px. "
        "If it only works at 24, it does not work.</footer>",
        "</div>",
        f"<script>{SHEET_JS}</script>",
    ]
    return "\n".join(out) + "\n"


