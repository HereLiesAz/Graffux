def notice(icons):
    """Third-party attribution, generated so the list of borrowed icons cannot go stale."""
    borrowed = sorted((ic["key"], ic["source"].split("/", 1)[1])
                      for ic in icons if ic["source"].startswith("phosphor/"))
    mine = len(icons) - len(borrowed)
    out = [
        "Third-party notices for the Graffux icon set",
        "============================================",
        "",
        f"{len(borrowed)} of the {len(icons)} icons in this set are drawings from Phosphor Icons, used as",
        f"delivered. The remaining {mine} are Graffux's own.",
        "",
        "Phosphor's licence is MIT, which requires this notice to travel with any copy of the",
        "geometry — a shipped app binary included, not only this repository. It is generated by",
        "branding/icons/build.py from the set's own manifest, so the list below cannot drift",
        "from what actually ships, and a copy is written to the app's resources.",
        "",
        "",
        "Phosphor Icons",
        "--------------",
        "",
        "https://github.com/phosphor-icons/core",
        "",
        PHOSPHOR_MIT,
        "",
        "",
        "Which icons",
        "-----------",
        "",
        f"The {len(borrowed)} Graffux keys below are Phosphor drawings. Each is also recorded in",
        "dist/icons.json and in the comment at the top of its master.",
        "",
    ]
    width = max(len(k) for k, _ in borrowed)
    out += [f"  {k.ljust(width)}  {n}" for k, n in borrowed]
    return "\n".join(out) + "\n"


def clean_stale(icons):
    live = {res_name(ic["key"]) + ".xml" for ic in icons}
    removed = 0
    if os.path.isdir(DRAWABLE_DIR):
        for fn in os.listdir(DRAWABLE_DIR):
            if fn.startswith(PREFIX) and fn not in live:
                os.remove(os.path.join(DRAWABLE_DIR, fn))
                removed += 1
    return removed


def main():
    icons = load()
    errors, warnings = validate(icons)
    for w in warnings:
        print(f"  warn  {w}")
    if errors:
        for e in errors:
            print(f"  ERROR {e}", file=sys.stderr)
        return 1

    os.makedirs(DIST, exist_ok=True)
    os.makedirs(DRAWABLE_DIR, exist_ok=True)
    stale = clean_stale(icons)

    for ic in icons:
        with open(os.path.join(DRAWABLE_DIR, res_name(ic["key"]) + ".xml"), "w", encoding="utf-8") as fh:
            fh.write(vector_drawable(ic))

    manifest = {
        "grid": {
            "view": VIEW, "live": list(LIVE), "stroke": STROKE, "cap": CAP, "join": JOIN,
            "hatch": {"pitch": HATCH_PITCH, "weight": HATCH_WEIGHT, "phase": HATCH_PHASE},
        },
        "categories": [{"key": k, "title": t, "blurb": b} for k, t, b in CATEGORIES],
        "icons": [
            {
                "key": ic["key"],
                "category": ic["cat"],
                "drawable": res_name(ic["key"]),
                "keywords": ic["kw"],
                "master": f"masters/{ic['key']}.svg",
                "ruled": any(sh.ruled for sh in ic["shapes"]),
                "source": ic["source"],
            }
            for ic in icons
        ],
    }
    with open(os.path.join(DIST, "icons.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
        fh.write("\n")

    with open(os.path.join(DIST, "contact-sheet.html"), "w", encoding="utf-8") as fh:
        fh.write(contact_sheet(icons))

    os.makedirs(os.path.dirname(KOTLIN_PATH), exist_ok=True)
    with open(KOTLIN_PATH, "w", encoding="utf-8") as fh:
        fh.write(kotlin_registry(icons))

    text = notice(icons)
    os.makedirs(os.path.dirname(NOTICE_RES), exist_ok=True)
    for path in (NOTICE_PATH, NOTICE_RES):
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)

    counts = {}
    for ic in icons:
        counts[ic["cat"]] = counts.get(ic["cat"], 0) + 1
    borrowed = sum(1 for ic in icons if ic["source"].startswith("phosphor"))
    ruled = sum(1 for ic in icons if any(sh.ruled for sh in ic["shapes"]))
    print(f"\n{len(icons)} icons across {len(counts)} families"
          + (f", {stale} stale drawable(s) removed" if stale else ""))
    for k, t, _ in CATEGORIES:
        if k in counts:
            print(f"  {counts[k]:>4}  {t}")
    print(f"\n{ruled} ruled, {borrowed} drawn by Phosphor (MIT — see NOTICE)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
