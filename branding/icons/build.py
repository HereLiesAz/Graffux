def hatch_id(key: str) -> str:
    return "gfxHatch-" + key


def _num(v):
    return svgpath.fmt(v)


def svg_defs(key, icon_shapes, indent="  "):
    if not any(sh.ruled for sh in icon_shapes):
        return ""
    y = HATCH_PHASE * HATCH_PITCH
    return (
        f"{indent}<defs>\n"
        f'{indent}  <pattern id="{hatch_id(key)}" patternUnits="userSpaceOnUse"\n'
        f'{indent}           width="{_num(HATCH_PITCH * 4)}" height="{_num(HATCH_PITCH)}">\n'
        f'{indent}    <line x1="0" y1="{_num(y)}" x2="{_num(HATCH_PITCH * 4)}" y2="{_num(y)}"\n'
        f'{indent}          stroke="currentColor" stroke-width="{HATCH_WEIGHT}"/>\n'
        f"{indent}  </pattern>\n"
        f"{indent}</defs>\n"
    )


def svg_body(shapes, indent="  "):
    out = []
    for sh in shapes:
        attrs = [f'd="{sh.d}"']
        if sh.fill != "none":
            attrs.append(f'fill="{sh.fill}"')
        if sh.stroke == "none":
            attrs.append('stroke="none"')
        for k, v in sh.extras.items():
            attrs.append(f'{k}="{v}"')
        out.append(f"{indent}<path " + " ".join(attrs) + "/>")
    return "\n".join(out)


def vector_drawable(ic):
    key = ic["key"]
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- " + GENERATED + " -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{int(VIEW)}dp"',
        f'    android:height="{int(VIEW)}dp"',
        f'    android:viewportWidth="{int(VIEW)}"',
        f'    android:viewportHeight="{int(VIEW)}"',
        '    android:tint="?attr/colorControlNormal">',
        f"    <!-- {key} — {ic['source']} -->",
    ]
    for sh in ic["shapes"]:
        if sh.ruled:
            lines += vector_hatch(sh)
        elif sh.fill != "none":
            lines += ["    <path", '        android:fillColor="@android:color/white"']
            if sh.extras.get("fill-rule") == "evenodd":
                lines.append('        android:fillType="evenOdd"')
            lines.append(f'        android:pathData="{sh.d}" />')
        # A path can be both filled and stroked, so the stroke is its own emission rather
        # than an else-branch — dropping it silently un-outlines every ruled container.
        if sh.stroke != "none":
            lines += [
                "    <path",
                '        android:fillColor="@android:color/transparent"',
                '        android:strokeColor="@android:color/white"',
                f'        android:strokeWidth="{sh.extras.get("stroke-width", STROKE)}"',
                f'        android:strokeLineCap="{sh.extras.get("stroke-linecap", CAP)}"',
                f'        android:strokeLineJoin="{sh.extras.get("stroke-linejoin", JOIN)}"',
                f'        android:pathData="{sh.d}" />',
            ]
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def vector_hatch(sh):
    """A ruled region, as a clipped group of real lines.

    VectorDrawable has no pattern fill, so the rules have to be geometry. They are clipped
    to the region rather than trimmed to it, which keeps the line coordinates on the shared
    viewport grid — the same rules the SVG pattern lays down, at the same y values.

    Two consequences worth knowing before shipping a change here: the drawables get longer
    (a full-height region is twenty-odd extra paths), and VectorDrawable clip paths are not
    antialiased on every Android version, so a ruled edge can look harder than its SVG.
    """
    x0, y0, x1, y1 = sh.bbox()
    out = ["    <group>", f'        <clip-path android:pathData="{sh.d}" />']
    for y in hatch_lines(y0, y1):
        out += [
            "        <path",
            '            android:strokeColor="@android:color/white"',
            f'            android:strokeWidth="{HATCH_WEIGHT}"',
            f'            android:pathData="M{_num(x0)},{_num(y)}L{_num(x1)},{_num(y)}" />',
        ]
    out.append("    </group>")
    return out


def kotlin_registry(icons):
    cat_enum = ", ".join(c[0].upper() for c in CATEGORIES)
    props, entries = [], []
    for ic in icons:
        props.append(f"    /** `{ic['key']}` — {ic['cat']}. */")
        props.append(f"    val {pascal(ic['key'])}: Int get() = R.drawable.{res_name(ic['key'])}")
        kw = ", ".join(f'"{k}"' for k in ic["kw"])
        entries.append(
            f'        GxIcon("{ic["key"]}", R.drawable.{res_name(ic["key"])}, '
            f"GxIconCategory.{ic['cat'].upper()}, listOf({kw})),"
        )
    ruled = sum(1 for ic in icons if any(sh.ruled for sh in ic["shapes"]))
    return "\n".join([
        "package com.hereliesaz.graffitixr.design",
        "",
        "import androidx.annotation.DrawableRes",
        "",
        "// " + GENERATED,
        "",
        "/** The families the Graffux icon set is divided into. */",
        f"enum class GxIconCategory {{ {cat_enum} }}",
        "",
        "/** One icon: its stable key, its drawable, and what it can be searched by. */",
        "data class GxIcon(",
        "    val key: String,",
        "    @param:DrawableRes val res: Int,",
        "    val category: GxIconCategory,",
        "    val keywords: List<String>,",
        ")",
        "",
        "/**",
        " * The Graffux icon set.",
        " *",
        f" * {len(icons)} glyphs on a {int(VIEW)}-unit grid at one {STROKE}-unit stroke weight, outline first.",
        f" * {ruled} of them rule a region rather than filling it: rows of parallel lines at a fixed",
        " * pitch, anchored to the viewport rather than to the region, so that any two ruled icons",
        " * side by side read as ruled from the same plate.",
        " *",
        " * Reference them directly (`GraffuxIcons.Brush`) or look them up by key for a picker.",
        " */",
        "object GraffuxIcons {",
        "",
        "\n".join(props),
        "",
        "    /** Every icon, grouped by family. */",
        "    val all: List<GxIcon> = listOf(",
        "\n".join(entries),
        "    )",
        "",
        "    private val byKey: Map<String, GxIcon> = all.associateBy { it.key }",
        "",
        "    /** Look an icon up by its stable key, e.g. `\"layer-mask-add\"`. */",
        "    operator fun get(key: String): GxIcon? = byKey[key]",
        "",
        "    /** Every icon in one family, in authored order. */",
        "    fun inCategory(category: GxIconCategory): List<GxIcon> = all.filter { it.category == category }",
        "",
        "    /** Case-insensitive search across keys and keywords, for an icon picker. */",
        "    fun search(query: String): List<GxIcon> {",
        "        val q = query.trim().lowercase()",
        "        if (q.isEmpty()) return all",
        "        return all.filter { icon ->",
        "            icon.key.contains(q) || icon.keywords.any { it.contains(q) }",
        "        }",
        "    }",
        "}",
        "",
    ])


