"""Build every icon output from the masters.

The masters in `masters/` are the drawings; this turns them into the three things that ship:
an Android VectorDrawable per icon, a typed Kotlin registry, and a contact sheet to review
them on. Nothing here draws anything — a change to a glyph is a change to its master.

The drawings arrive from a design package rather than being generated here, which moves the
job from *emitting* geometry to *checking* it. Two of the checks earn their place:

**Bounds** are measured off flattened curves, not control points. A Bézier's control polygon
can sit most of a unit outside the curve it describes, so control-point bounds flag glyphs
that are fine and miss glyphs that are not.

**Collisions** are found by rendering, not by comparing markup. Two icons in the delivered
set differed only by a line drawn exactly along an edge another shape already had; several
more differed only in `<circle>` elements, which a scan of `d` attributes cannot see at all.
A silhouette hash over the drawn geometry catches both, and it is the check that matters
most here: 404 icons is well past the number anyone can hold in their head, and two keys
that look the same are indistinguishable to the person using the app.
"""

