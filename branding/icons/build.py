def silhouette(ic) -> str:
    """A hash of what the icon actually draws, ignoring how the file says it.

    Geometry is flattened first, so a circle written as `<circle>`, as two arcs, or as four
    cubics all hash alike, and rounded to a fifth of a unit so that a coordinate rewritten
    at a different precision is not mistaken for a different drawing. Fill and stroke are
    folded in: two identical outlines, one ruled and one not, are two different drawings.
    """
    marks = []
    for sh in ic["shapes"]:
        pts = ";".join(f"{round(x * 5) / 5:g},{round(y * 5) / 5:g}"
                       for poly in sh.polys for x, y in poly)
        kind = "ruled" if sh.ruled else ("filled" if sh.fill != "none" else "")
        marks.append(f"{kind}|{'stroked' if sh.stroke != 'none' else ''}|{pts}")
    return hashlib.md5("\n".join(sorted(marks)).encode()).hexdigest()


def validate(icons):
    errors, warnings = [], []
    for ic in icons:
        key = ic["key"]
        if not key.replace("-", "").isalnum() or not key[0].isalpha():
            errors.append(f"{key}: key must be alphanumeric kebab-case starting with a letter")
        if ic["cat"] not in {c for c, _, _ in CATEGORIES}:
            errors.append(f"{key}: category {ic['cat']!r} is not one of the {len(CATEGORIES)} families")

        boxes = [sh.bbox() for sh in ic["shapes"] if sh.bbox()]
        if not boxes:
            errors.append(f"{key}: empty glyph")
            continue
        x0 = min(b[0] for b in boxes); y0 = min(b[1] for b in boxes)
        x1 = max(b[2] for b in boxes); y1 = max(b[3] for b in boxes)
        if x0 < BLEED[0] - 1e-6 or y0 < BLEED[0] - 1e-6 or x1 > BLEED[1] + 1e-6 or y1 > BLEED[1] + 1e-6:
            errors.append(f"{key}: geometry {x0:.2f},{y0:.2f}..{x1:.2f},{y1:.2f} escapes the bleed {BLEED}")
        elif x0 < LIVE[0] - 1e-6 or y0 < LIVE[0] - 1e-6 or x1 > LIVE[1] + 1e-6 or y1 > LIVE[1] + 1e-6:
            warnings.append(f"{key}: geometry reaches into the bleed margin")
        if (x1 - x0) < 6 and (y1 - y0) < 6:
            warnings.append(f"{key}: glyph is only {x1 - x0:.1f}×{y1 - y0:.1f} — too small to read as deliberate")

        weight = sum(len(sh.d) for sh in ic["shapes"])
        outlined = any(sh.stroke != "none" for sh in ic["shapes"])
        budget = BUDGET if outlined else BUDGET_FILLED
        if weight > budget:
            warnings.append(f"{key}: {weight} chars of path data (budget {budget}) — cut something")

        for sh in ic["shapes"]:
            if sh.ruled and sh.fill != f"url(#{hatch_id(key)})":
                errors.append(f"{key}: ruled path points at {sh.fill}, not this icon's own pattern")

    # Two keys that draw the same thing are indistinguishable in a picker, whatever the
    # markup says. This is an error, not a warning: it always means one of them is wrong.
    seen = {}
    for ic in icons:
        seen.setdefault(silhouette(ic), []).append(ic["key"])
    for group in seen.values():
        if len(group) > 1:
            errors.append("identical drawings: " + " = ".join(sorted(group)))
    return errors, warnings


