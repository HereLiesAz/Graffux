class Shape:
    """One drawn path, with its fill and stroke already resolved."""

    __slots__ = ("d", "fill", "stroke", "extras", "_polys")

    def __init__(self, d, fill, stroke, extras):
        self.d, self.fill, self.stroke, self.extras = d, fill, stroke, extras
        self._polys = None

    @property
    def polys(self):
        if self._polys is None:
            self._polys = svgpath.flatten(svgpath.parse(self.d))
        return self._polys

    @property
    def ruled(self) -> bool:
        return self.fill.startswith("url(")

    def bbox(self):
        return svgpath.bbox(self.polys)


def read_master(path, key):
    root = ET.parse(path).getroot()
    vb = root.get("viewBox", "").split()
    if [float(v) for v in vb] != [0.0, 0.0, VIEW, VIEW]:
        raise ValueError(f"viewBox is {root.get('viewBox')!r}, expected 0 0 {int(VIEW)} {int(VIEW)}")
    shapes = []
    for el in root:
        if el.tag.split("}")[-1] != "path":
            continue
        d = el.get("d")
        if not d:
            continue
        extras = {k: v for k, v in el.attrib.items()
                  if k in ("fill-rule", "stroke-width", "stroke-linecap", "stroke-linejoin")}
        shapes.append(Shape(d, el.get("fill", "none"), el.get("stroke", "currentColor"), extras))
    if not shapes:
        raise ValueError("no paths")
    return shapes


def load():
    meta = json.load(open(META_PATH, encoding="utf-8"))
    order = {k: i for i, (k, _, _) in enumerate(CATEGORIES)}
    icons = []
    for fn in sorted(os.listdir(MASTERS)):
        if not fn.endswith(".svg"):
            continue
        key = fn[:-4]
        info = meta.get(key)
        if info is None:
            raise SystemExit(f"{key}: no entry in meta.json — re-run import_package.py")
        icons.append({
            "key": key,
            "cat": info["category"],
            "kw": info.get("keywords", []),
            "source": info.get("source", "graffux"),
            "shapes": read_master(os.path.join(MASTERS, fn), key),
        })
    icons.sort(key=lambda ic: (order.get(ic["cat"], 99), ic["key"]))
    return icons


