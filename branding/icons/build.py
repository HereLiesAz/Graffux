def clean_stale(icons):
    """Remove drawables from a previous run whose icon no longer exists."""
    live = {res_name(ic["key"]) + ".xml" for ic in icons}
    removed = 0
    if os.path.isdir(DRAWABLE_DIR):
        for fn in os.listdir(DRAWABLE_DIR):
            if fn.startswith(PREFIX) and fn not in live:
                os.remove(os.path.join(DRAWABLE_DIR, fn))
                removed += 1
    if os.path.isdir(SVG_DIR):
        live_svg = {ic["key"] + ".svg" for ic in icons}
        for fn in os.listdir(SVG_DIR):
            if fn.endswith(".svg") and fn not in live_svg:
                os.remove(os.path.join(SVG_DIR, fn))
    return removed


def main():
    errors, warnings = validate(ICONS)
    for w in warnings:
        print(f"  warn  {w}")
    if errors:
        for e in errors:
            print(f"  ERROR {e}", file=sys.stderr)
        return 1

    os.makedirs(SVG_DIR, exist_ok=True)
    os.makedirs(DRAWABLE_DIR, exist_ok=True)

    stale = clean_stale(ICONS)

    for ic in ICONS:
        with open(os.path.join(SVG_DIR, ic["key"] + ".svg"), "w", encoding="utf-8") as fh:
            fh.write(svg_document(ic))
        with open(os.path.join(DRAWABLE_DIR, res_name(ic["key"]) + ".xml"), "w", encoding="utf-8") as fh:
            fh.write(vector_drawable(ic))

    manifest = {
        "grid": {"view": VIEW, "live": list(LIVE), "stroke": STROKE, "cap": CAP, "join": JOIN},
        "categories": [{"key": k, "title": t, "blurb": b} for k, t, b in CATEGORIES],
        "icons": [
            {
                "key": ic["key"],
                "category": ic["cat"],
                "drawable": res_name(ic["key"]),
                "keywords": ic["kw"],
                "apps": ic["apps"],
                "basis": ic["basis"],
                "note": ic["note"],
            }
            for ic in ICONS
        ],
    }
    with open(os.path.join(DIST, "icons.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
        fh.write("\n")

    with open(os.path.join(DIST, "contact-sheet.html"), "w", encoding="utf-8") as fh:
        fh.write(contact_sheet(ICONS))

    os.makedirs(os.path.dirname(KOTLIN_PATH), exist_ok=True)
    with open(KOTLIN_PATH, "w", encoding="utf-8") as fh:
        fh.write(kotlin_registry(ICONS))

    counts, weights = {}, []
    for ic in ICONS:
        counts[ic["cat"]] = counts.get(ic["cat"], 0) + 1
        weights.append((sum(len(p.d) for p in ic["strokes"] + ic["fills"]), ic["key"]))
    weights.sort(reverse=True)
    print(f"\n{len(ICONS)} icons across {len(counts)} families"
          + (f", {stale} stale drawable(s) removed" if stale else ""))
    for k, t, _ in CATEGORIES:
        if k in counts:
            print(f"  {counts[k]:>4}  {t}")
    total = sum(w for w, _ in weights)
    print(f"\npath data: {total} chars total, {total // len(weights)} mean, "
          f"heaviest {weights[0][1]} at {weights[0][0]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
