HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

from kit import BLEED, BUDGET, CAP, ICONS, JOIN, LIVE, STROKE, VIEW, CATEGORIES  # noqa: E402

import sets  # noqa: E402,F401  (importing the package registers every icon)

DIST = os.path.join(HERE, "dist")
SVG_DIR = os.path.join(DIST, "svg")
DRAWABLE_DIR = os.path.join(ROOT, "core", "design", "src", "main", "res", "drawable")
KOTLIN_PATH = os.path.join(
    ROOT, "core", "design", "src", "main", "java", "com", "hereliesaz", "graffitixr",
    "design", "GraffuxIcons.kt",
)

PREFIX = "ic_gx_"
GENERATED = "Generated by branding/icons/build.py — edit the geometry in branding/icons/sets/, not this file."


# ---------------------------------------------------------------------------------------
# Naming
# ---------------------------------------------------------------------------------------


def res_name(key: str) -> str:
    return PREFIX + key.replace("-", "_")


def pascal(key: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in key.split("-"))


# ---------------------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------------------


def validate(icons):
    errors, warnings = [], []
    for ic in icons:
        key = ic["key"]
        if not ic["strokes"] and not ic["fills"]:
            errors.append(f"{key}: empty glyph")
            continue
        if not key.replace("-", "").isalnum() or not key[0].isalpha():
            errors.append(f"{key}: key must be alphanumeric kebab-case starting with a letter")
        if len(ic["fills"]) > 1:
            warnings.append(f"{key}: {len(ic['fills'])} fill paths — an icon gets one keystone")

        pts = [p for path in ic["strokes"] + ic["fills"] for p in path.pts]
        xs = [p[0] for p in pts]
        ys = [p[1] for p in pts]
        x0, y0, x1, y1 = min(xs), min(ys), max(xs), max(ys)
        if x0 < BLEED[0] - 1e-6 or y0 < BLEED[0] - 1e-6 or x1 > BLEED[1] + 1e-6 or y1 > BLEED[1] + 1e-6:
            errors.append(f"{key}: geometry {x0:.2f},{y0:.2f}..{x1:.2f},{y1:.2f} escapes the bleed {BLEED}")
        elif x0 < LIVE[0] - 1e-6 or y0 < LIVE[0] - 1e-6 or x1 > LIVE[1] + 1e-6 or y1 > LIVE[1] + 1e-6:
            warnings.append(f"{key}: geometry reaches into the bleed margin")

        # An icon that occupies a corner of the grid and nothing else reads as broken at 16px.
        if (x1 - x0) < 6 and (y1 - y0) < 6:
            warnings.append(f"{key}: glyph is only {x1 - x0:.1f}×{y1 - y0:.1f} — too small to read as deliberate")

        # Minimalism is a constraint, not a preference: a glyph that needs more than a
        # couple of hundred characters of path data is describing, not signalling.
        weight = sum(len(p.d) for p in ic["strokes"] + ic["fills"])
        if weight > BUDGET:
            warnings.append(f"{key}: {weight} chars of path data (budget {BUDGET}) — cut something")

        # Anything the three apps already have must say whose metaphor it inherits.
        if ic["apps"] != "new" and not ic["basis"]:
            errors.append(f"{key}: claims lineage ({ic['apps']}) but records no basis")
        # "new" + basis is fine when the lineage is Graffux's own (GraffitiXR) or a named
        # feature none of PS/AI/PR actually ships as an icon — only flag the ambiguous case
        # where the basis text itself claims one of the three apps' tools.
        if ic["apps"] == "new" and ic["basis"] and any(
            app in ic["basis"] for app in ("Photoshop's", "Illustrator's", "Procreate's")
        ):
            warnings.append(f"{key}: basis names an app tool but apps is \"new\" — check attribution")
    return errors, warnings


# ---------------------------------------------------------------------------------------
# Emitters
# ---------------------------------------------------------------------------------------


def svg_body(ic, indent="  "):
    out = []
    for p in ic["strokes"]:
        out.append(f'{indent}<path d="{p.d}"/>')
    for p in ic["fills"]:
        rule = ' fill-rule="evenodd"' if p.evenodd else ""
        out.append(f'{indent}<path d="{p.d}" fill="currentColor" stroke="none"{rule}/>')
    return "\n".join(out)


def svg_document(ic):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {int(VIEW)} {int(VIEW)}"\n'
        f'     width="{int(VIEW)}" height="{int(VIEW)}" fill="none" stroke="currentColor"\n'
        f'     stroke-width="{STROKE}" stroke-linecap="{CAP}" stroke-linejoin="{JOIN}">\n'
        f"  <!-- graffux/{ic['key']} — {ic['note']} -->\n"
        f"{svg_body(ic)}\n"
        f"</svg>\n"
    )


def vector_drawable(ic):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- " + GENERATED + " -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{int(VIEW)}dp"',
        f'    android:height="{int(VIEW)}dp"',
        f'    android:viewportWidth="{int(VIEW)}"',
        f'    android:viewportHeight="{int(VIEW)}"',
        '    android:tint="?attr/colorControlNormal">',
        f"    <!-- {ic['key']}: {ic['note']} -->",
    ]
    if ic["basis"]:
        lines.append(f"    <!-- lineage ({ic['apps']}): {ic['basis']} -->")
    for p in ic["strokes"]:
        lines += [
            "    <path",
            '        android:fillColor="@android:color/transparent"',
            '        android:strokeColor="@android:color/white"',
            f'        android:strokeWidth="{STROKE}"',
            f'        android:strokeLineCap="{CAP}"',
            f'        android:strokeLineJoin="{JOIN}"',
            f'        android:pathData="{p.d}" />',
        ]
    for p in ic["fills"]:
        lines += [
            "    <path",
            '        android:fillColor="@android:color/white"',
        ]
        if p.evenodd:
            lines.append('        android:fillType="evenOdd"')
        lines.append(f'        android:pathData="{p.d}" />')
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def kotlin_registry(icons):
    cat_enum = ", ".join(c[0].upper() for c in CATEGORIES)
    props, entries = [], []
    for ic in icons:
        name = pascal(ic["key"])
        note = ic["note"].replace("*/", "*\\/")
        props.append(f"    /** {note} */")
        props.append(f"    val {name}: Int get() = R.drawable.{res_name(ic['key'])}")
        kw = ", ".join(f'"{k}"' for k in ic["kw"])
        entries.append(
            f'        GxIcon("{ic["key"]}", R.drawable.{res_name(ic["key"])}, '
            f"GxIconCategory.{ic['cat'].upper()}, listOf({kw})),"
        )
    return "\n".join(
        [
            "package com.hereliesaz.graffitixr.design",
            "",
            "import androidx.annotation.DrawableRes",
            "",
            "// " + GENERATED,
            "",
            "/** The families the Graffux icon set is divided into. */",
            f"enum class GxIconCategory {{ {cat_enum} }}",
            "",
            "/** One icon: its stable key, its drawable, and what it can be searched by. */",
            "data class GxIcon(",
            "    val key: String,",
            "    @param:DrawableRes val res: Int,",
            "    val category: GxIconCategory,",
            "    val keywords: List<String>,",
            ")",
            "",
            "/**",
            " * The Graffux icon set.",
            " *",
            f" * {len(icons)} glyphs on a 24-unit grid, one {STROKE}-unit stroke weight, at most one solid",
            " * mark each — the keystone, which always sits where the operation acts.",
            " *",
            " * Reference them directly (`GraffuxIcons.Brush`) or look them up by key for a picker.",
            " */",
            "object GraffuxIcons {",
            "",
            "\n".join(props),
            "",
            "    /** Every icon, in authored order — categories stay grouped. */",
            "    val all: List<GxIcon> = listOf(",
            "\n".join(entries),
            "    )",
            "",
            "    private val byKey: Map<String, GxIcon> = all.associateBy { it.key }",
            "",
            "    /** Look an icon up by its stable key, e.g. `\"layer-mask-add\"`. */",
            "    operator fun get(key: String): GxIcon? = byKey[key]",
            "",
            "    /** Every icon in one family, in authored order. */",
            "    fun inCategory(category: GxIconCategory): List<GxIcon> = all.filter { it.category == category }",
            "",
            "    /** Case-insensitive search across keys and keywords, for an icon picker. */",
            "    fun search(query: String): List<GxIcon> {",
            "        val q = query.trim().lowercase()",
            "        if (q.isEmpty()) return all",
            "        return all.filter { icon ->",
            "            icon.key.contains(q) || icon.keywords.any { it.contains(q) }",
            "        }",
            "    }",
            "}",
            "",
        ]
    )


