package com.hereliesaz.graffitixr.design

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.graphics.vector.group
import androidx.compose.ui.unit.dp

/**
 * The rails' glyphs, ported path for path from the approved rail mockup (the "Graffux UI Rework"
 * canvas). Each one keeps the mockup's 24-unit viewBox, its 1.8 stroke and the SVG defaults it
 * relied on (butt caps, miter joins, no fill). Draw them at 22dp, the size the mockup draws them.
 *
 * They are written by hand, not generated by branding/icons/build.py, so this file is separate from
 * [GraffuxIcons]. The strokes are white so that an `Icon` tint recolours them.
 */
object RailIcons {

    private const val STROKE = 1.8f

    private fun stroked(name: String, vararg paths: String, width: Float = STROKE, round: Boolean = false): ImageVector =
        ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).apply {
            paths.forEach { d ->
                addPath(
                    pathData = addPathNodes(d),
                    fill = null,
                    stroke = SolidColor(Color.White),
                    strokeLineWidth = width,
                    strokeLineCap = if (round) StrokeCap.Round else StrokeCap.Butt,
                    strokeLineJoin = StrokeJoin.Miter,
                    strokeLineMiter = 4f,
                )
            }
        }.build()

    /** Paint bucket. */
    val Fill: ImageVector by lazy { stroked("rail.fill", "M4 12l7-7 8 8-7 7z", "M19 15c1 2 2 3 1 4s-2 0-1-4z") }

    /** A curve between two square handles. The SVG's `<rect>`s are written as closed paths. */
    val Vector: ImageVector by lazy {
        stroked("rail.vector", "M4 20C8 8 16 16 20 4", "M2 18h4v4h-4z", "M18 2h4v4h-4z")
    }

    /**
     * The marquee: `<rect x=4 y=4 w=16 h=16>` with `stroke-dasharray: 3 3`. An ImageVector has no
     * dash, so the dashes are written out: every 3 units on, 3 off, clockwise from the top-left,
     * the one that turns the bottom-right corner keeping its corner.
     */
    val Select: ImageVector by lazy {
        stroked(
            "rail.select",
            "M4 4L7 4M10 4L13 4M16 4L19 4M20 6L20 9M20 12L20 15M20 18L20 20L19 20M16 20L13 20M10 20L7 20M4 20L4 17M4 14L4 11M4 8L4 5",
        )
    }

    /** Four-way move arrows. */
    val Transform: ImageVector by lazy {
        stroked("rail.transform", "M12 3v18M3 12h18M12 3l-3 3M12 3l3 3M21 12l-3-3M21 12l-3 3")
    }

    val Undo: ImageVector by lazy { stroked("rail.undo", "M9 14L4 9l5-5", "M4 9h10a6 6 0 010 12h-3") }

    val Redo: ImageVector by lazy { stroked("rail.redo", "M15 14l5-5-5-5", "M20 9H10a6 6 0 000 12h3") }

    /** New layer. */
    val Plus: ImageVector by lazy { stroked("rail.plus", "M12 5v14M5 12h14") }

    /** The hidden-layer badge: stroke 2.2, round caps. */
    val EyeOff: ImageVector by lazy {
        stroked(
            "rail.eyeOff",
            "M3 3l18 18M10.6 6.1A10 10 0 0122 12a17 17 0 01-3 3.6M6.2 6.2A17 17 0 002 12s4 7 10 7a10 10 0 004.2-.9",
            width = 2.2f,
            round = true,
        )
    }

    /**
     * The Graffux mark in its own colours (draw it with `Image`, not a tinted `Icon`). The SVG's
     * viewBox is 96 96 320 320, so everything is shifted by −96.
     */
    val LogoMark: ImageVector by lazy {
        ImageVector.Builder("rail.logo", 26.dp, 26.dp, 320f, 320f).apply {
            group(translationX = -96f, translationY = -96f) {
                addPath(
                    pathData = addPathNodes("m334.5 177.5l-157 157"),
                    stroke = SolidColor(Color(0xFF00E0D0)),
                    strokeLineWidth = 92.2f,
                    strokeLineCap = StrokeCap.Round,
                )
                addPath(
                    pathData = addPathNodes("m177.5 177.5l157 157"),
                    stroke = SolidColor(Color(0xFFFF2D78)),
                    strokeLineWidth = 92.2f,
                    strokeLineCap = StrokeCap.Round,
                )
                addPath(
                    pathData = addPathNodes(
                        "m315 135.9c23 7 15.9 123.8 14.4 146.4-1.4 32.6-19.8 37.6-19.8 61.4 0 6.4 2.5 12.5 7 16.9 4.5 4.5 10.6 7 16.9 7 6.3 0 12.4-2.5 16.9-7 4.5-4.4 7-10.5 7-16.9 0-23.8-18.4-24.8-19.8-61.4-0.6-26.3-7.6-150.4 19.4-144.4-7-6-32-8-42-2z",
                    ),
                    fill = SolidColor(Color.White),
                )
            }
        }.build()
    }
}
